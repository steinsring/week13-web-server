#!/bin/sh
# 서버 자체는 열세 인자를 생략할 수 없다.
PORT=8080
ROOT=./public
WORKERS=4
QUEUE_LIMIT=128
CONNECTION_LIMIT=100
BODY_LIMIT=1048576
BODY_TIMEOUT=30
KEEP_ALIVE_TIMEOUT=10
KEEP_ALIVE_MAX_REQUESTS=100
PUBLIC_URL=http://localhost:8080
PROXY_CONNECT_TIMEOUT=5
PROXY_RESPONSE_TIMEOUT=10
BACKENDS=http://127.0.0.1:8001,http://127.0.0.1:8002

# 따옴표는 공백이 있는 루트 경로도 한 인자로 유지한다.
# exec로 셸을 대체하여 종료 신호가 서버에 직접 도착하게 한다.
exec ./server "$PORT" "$ROOT" "$WORKERS" "$QUEUE_LIMIT" "$CONNECTION_LIMIT" "$BODY_LIMIT" "$BODY_TIMEOUT" "$KEEP_ALIVE_TIMEOUT" "$KEEP_ALIVE_MAX_REQUESTS" "$PUBLIC_URL" "$PROXY_CONNECT_TIMEOUT" "$PROXY_RESPONSE_TIMEOUT" "$BACKENDS"
